// 자주 나오는 낱말 → 영어 (긴 낱말부터 바꿈)
const WORDS = [
  ['자연휴양림', 'Natural Recreation Forest'], ['생태체험장', 'Eco Experience Park'], ['해수욕장', 'Beach'], ['관광농원', 'Tourist Farm'],
  ['야영장', 'Campground'], ['캠핑장', 'Campsite'], ['글램핑', 'Glamping'], ['카라반', 'Caravan'], ['캠핑', 'Camping'], ['캠프', 'Camp'],
  ['풀빌라', 'Pool Villa'], ['마을회', 'Village Association'], ['유한회사', 'Co., Ltd.'], ['서귀포점', 'Seogwipo Branch'], ['애월점', 'Aewol Branch'],
  ['펜션', 'Pension'], ['리조트', 'Resort'], ['숲속', 'Forest'], ['오름', 'Oreum'], ['제주', 'Jeju'],
];
const HANGUL = /[가-힣]+/g;

function autoName(ko = '') {
  let s = ko;
  for (const [k, v] of WORDS) s = s.split(k).join(` ${v} `);
  s = s.replace(HANGUL, (m) => ` ${m.split('').map((c) => romanize(c)).join('').replace(/^./, (x) => x.toUpperCase())} `);
  return s.replace(/\s+/g, ' ').replace(/\s+([)\]],.])/g, '$1').replace(/([([])\s+/g, '$1').trim();
}

export const campNameEn = (c) => CAMP_NAMES_EN[c.id] ?? autoName(c.name);

// 선택한 언어의 이름: 중국어·일본어 사전에 없으면(새 캠핑장) 영문 이름으로
export const campName = (c, lang) => (lang === 'zh' ? CAMP_NAMES_ZH[c.id] : lang === 'ja' ? CAMP_NAMES_JA[c.id] : undefined) ?? campNameEn(c);
